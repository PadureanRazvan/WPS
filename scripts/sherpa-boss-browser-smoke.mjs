import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// Run against scripts/experience-studio.mjs only: its Firebase is an offline fixture.
// SHERPA_PLAYWRIGHT_PATH may point to the installed Playwright package directory.
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.SHERPA_PLAYWRIGHT_PATH || 'playwright');
const base = process.argv.find(value => value.startsWith('--url='))?.slice(6) || 'http://127.0.0.1:4173';
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(base).hostname), 'Use the offline preview only.');
const output = resolve(import.meta.dirname, '../output/sherpa-boss');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const results = [], errors = [];
try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}/?session=ready`);
    await page.waitForSelector('#chatBubble[data-boss-renderer="three"]');
    await page.addStyleTag({ content: '#experience-preview{display:none!important}' });
    const boss = page.locator('#chatBubble');
    const start = await boss.boundingBox();
    const from = { x: start.x + start.width / 2, y: start.y + start.height * .3 };
    await page.mouse.move(from.x, from.y); await page.mouse.down();
    await page.mouse.move(from.x - 380, from.y - 220, { steps: 15 });
    assert.equal(await boss.getAttribute('data-boss-dragging'), 'true');
    await page.screenshot({ path: resolve(output, 'ragdoll-drag.png') });
    await page.mouse.up();
    assert.equal(await page.locator('#chatPanel').evaluate(el => el.classList.contains('open')), false, 'Throw must not open chat.');
    await page.waitForFunction(() => !document.querySelector('#chatBubble').hasAttribute('data-boss-reaction'), null, { timeout: 9000 });
    const landed = await boss.boundingBox();
    assert.ok(landed.x >= 0 && landed.x + landed.width <= 1440 && landed.y >= 0 && landed.y + landed.height <= 1000);
    results.push('Mouse throw, click suppression, gravity and viewport bounds');
    await boss.focus(); await page.keyboard.press('Home');
    assert.ok(Math.abs((await boss.boundingBox()).x - start.x) < 1);
    await page.keyboard.press('Enter');
    await page.waitForSelector('#chatPanel.open');
    assert.equal(await boss.getAttribute('aria-expanded'), 'true');
    assert.equal(await boss.isVisible(), false);
    await page.locator('#chatCloseBtn').click();
    await page.waitForFunction(() => !document.querySelector('#chatPanel').classList.contains('open'));
    assert.equal(await boss.isVisible(), true);
    results.push('Keyboard activation, close and focus return');
    await boss.click({ button: 'right' });
    await page.waitForSelector('[data-boss-preview][data-boss-renderer="three"]');
    for (const action of ['wave', 'dance', 'spin', 'celebrate']) {
        await page.locator(`[data-boss-action="${action}"]`).filter({ hasNot: page.locator('canvas') }).click();
        assert.equal(await page.locator('[data-boss-preview]').getAttribute('data-boss-action'), action);
        await page.waitForTimeout(750);
        await page.screenshot({ path: resolve(output, `${action}.png`) });
    }
    await page.locator('#bossTurn').fill('65');
    await page.waitForTimeout(2800);
    await page.screenshot({ path: resolve(output, 'studio-angle.png') });
    await page.locator('#bossTurn').fill('0');
    await page.locator('[data-boss-pause]').click();
    assert.equal(await page.locator('[data-boss-pause]').getAttribute('aria-pressed'), 'true');
    await page.screenshot({ path: resolve(output, 'studio-desktop.png') });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#bossStudio').evaluate(el => el.open), false);
    await boss.click({ button: 'right' });
    await page.waitForSelector('[data-boss-preview][data-boss-renderer="three"]');
    assert.equal(await page.locator('[data-boss-pause]').getAttribute('aria-pressed'), 'true');
    await page.locator('#bossTurn').fill('-45');
    await page.screenshot({ path: resolve(output, 'studio-reopened-paused.png') });
    await page.keyboard.press('Escape');
    results.push('All four animations, turntable, pause, native dialog Escape');
    await page.screenshot({ path: resolve(output, 'dashboard-desktop.png') });
    // A signed-out shell must not retain the WebGL launcher or an open studio.
    await page.locator('#logoutBtn').click();
    await page.waitForSelector('html[data-auth-state="signed-out"]');
    assert.equal(await boss.isVisible(), false);
    assert.equal(await page.locator('#bossStudio').evaluate(el => el.open), false);
    results.push('Logout hides companion and closes studio');
    await page.close();

    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 1 });
    mobile.on('pageerror', error => errors.push(error.message));
    await mobile.goto(`${base}/?session=ready`);
    await mobile.waitForSelector('#chatBubble[data-boss-renderer="three"]');
    await mobile.addStyleTag({ content: '#experience-preview{display:none!important}' });
    const mobileBoss = mobile.locator('#chatBubble');
    const r = await mobileBoss.boundingBox();
    const cdp = await mobile.context().newCDPSession(mobile);
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: r.x + 50, y: r.y + 40 }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 120, y: 350 }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    assert.equal(await mobile.locator('#chatPanel').evaluate(el => el.classList.contains('open')), false);
    await mobile.waitForFunction(() => !document.querySelector('#chatBubble').hasAttribute('data-boss-reaction'), null, { timeout: 9000 });
    await mobile.locator('#bossMinimize').tap();
    assert.equal(await mobile.locator('#bossDock').isVisible(), true);
    await mobile.locator('#bossDock').tap();
    assert.equal(await mobileBoss.isVisible(), true);
    await mobileBoss.tap();
    await mobile.waitForSelector('#chatPanel.open');
    const panel = await mobile.locator('#chatPanel').boundingBox();
    assert.ok(panel.x >= 0 && panel.x + panel.width <= 390 && panel.y >= 0 && panel.y + panel.height <= 844);
    assert.equal(await mobile.locator('#chatInput').isVisible(), true);
    await mobile.waitForTimeout(350);
    await mobile.screenshot({ path: resolve(output, 'chat-mobile.png') });
    await mobile.locator('#bossStudioBtn').tap();
    await mobile.waitForSelector('[data-boss-preview][data-boss-renderer="three"]');
    assert.ok(await mobile.locator('#bossStudio').evaluate(el => el.scrollWidth <= el.clientWidth));
    await mobile.screenshot({ path: resolve(output, 'studio-mobile.png') });
    results.push('390px touch drag/tap, minimize/restore, bounded chat input, scrollable studio');
    await mobile.close();

    const reduced = await browser.newPage({ viewport: { width: 360, height: 640 }, reducedMotion: 'reduce' });
    await reduced.goto(`${base}/?session=ready`);
    await reduced.waitForSelector('#chatBubble[data-boss-renderer="three"]');
    await reduced.addStyleTag({ content: '#experience-preview{display:none!important}' });
    await reduced.locator('#chatBubble').click();
    const small = await reduced.locator('#chatPanel').boundingBox();
    assert.ok(small.y >= 0 && small.y + small.height <= 640);
    await reduced.waitForTimeout(350);
    await reduced.screenshot({ path: resolve(output, 'chat-small-reduced-motion.png') });
    results.push('360px short viewport and reduced-motion launcher');
    await reduced.close();
    const fallback = await browser.newPage({ viewport: { width: 1000, height: 800 } });
    await fallback.route('**/assets/vendor/three.module.min.js', route => route.abort());
    await fallback.goto(`${base}/?session=ready&boss=dashboard`);
    await fallback.waitForSelector('#chatBubble[data-boss-renderer="fallback"]');
    assert.equal(await fallback.locator('#chatBubble .boss-fallback').isVisible(), true);
    await fallback.locator('#chatBubble').click();
    await fallback.waitForSelector('#chatPanel.open');
    results.push('Blocked graphics import retains local portrait and functional chat');
    await fallback.close();
    assert.deepEqual(errors, []);
    await writeFile(resolve(output, 'browser-results.json'), JSON.stringify({ results, errors }, null, 2));
    console.log(JSON.stringify({ results, errors }, null, 2));
} finally { await browser.close(); }
